function getLang() {
    return localStorage.getItem('rtbd_lang') || 'bn';
}

function setLang(lang) {
    localStorage.setItem('rtbd_lang', lang);
    applyLang();
    
    document.querySelectorAll('.lang-toggle .lt-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    
    setTimeout(() => {
        window.location.reload();
    }, 100);
}

function getRoleTranslation(role) {
    const roleMap = {
        'সাধারণ': { bn: 'সাধারণ নাগরিক', en: 'Citizen' },
        'স্বেচ্ছাসেবক': { bn: 'স্বেচ্ছাসেবক', en: 'Volunteer' },
        'ঠিকাদার': { bn: 'ঠিকাদার', en: 'Contractor' },
        'সরকারিকর্মকর্তা': { bn: 'সরকারি কর্মকর্তা', en: 'Govt. Official' }
    };
    const lang = getLang();
    return (roleMap[role] && roleMap[role][lang]) || role;
}

function t(key) {
    const lang = getLang();
    const entry = RTBD_TRANSLATIONS[key];
    if (!entry) return key;
    return entry[lang] || entry['bn'] || key;
}

function applyLang() {
    const lang = getLang();
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const entry = RTBD_TRANSLATIONS[key];
        if (!entry) return;
        const val = entry[lang] || entry['bn'] || key;
        
        if (val) {
            el.innerHTML = val;
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        const entry = RTBD_TRANSLATIONS[key];
        if (entry) el.placeholder = entry[lang] || entry['bn'] || key;
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.dataset.i18nTitle;
        const entry = RTBD_TRANSLATIONS[key];
        if (entry) el.title = entry[lang] || entry['bn'] || key;
    });

    // Dynamic Select Option Translation
    document.querySelectorAll('option').forEach(el => {
        const text = el.textContent.trim();
        if (lang === 'en') {
            if (DISTRICT_MAP[text]) {
                if (!el.dataset.origText) el.dataset.origText = text;
                el.textContent = DISTRICT_MAP[text];
            }
        } else {
            if (el.dataset.origText) {
                el.textContent = el.dataset.origText;
            }
        }
    });
}

function injectLangToggle(navSelector) {
    let target = null;
    if (navSelector === 'nav') {
        target = document.getElementById('navRight') || document.querySelector('nav');
    } else {
        target = document.querySelector(navSelector || '#navRight') || document.querySelector('nav');
    }
    if (!target || target.querySelector('.lang-toggle')) return;
    const toggle = document.createElement('div');
    toggle.className = 'lang-toggle';
    const lang = getLang();
    toggle.innerHTML = `
        <button class="lt-btn ${lang === 'bn' ? 'active' : ''}" data-lang="bn" onclick="setLang('bn')">বাং</button>
        <span class="lt-sep">|</span>
        <button class="lt-btn ${lang === 'en' ? 'active' : ''}" data-lang="en" onclick="setLang('en')">EN</button>
    `;
    
    target.appendChild(toggle);
}

document.addEventListener('DOMContentLoaded', () => {
    setTimeout(applyLang, 10);
});
